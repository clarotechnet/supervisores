const dates = Array.from({ length: 35 }, (_, i) => {
  const date = new Date(Date.UTC(2026, 11, i + 1));
  return date.toISOString().slice(0, 10);
});
export const CONTROL_DECEMBER_DATES = Object.freeze(dates);
export function controlDecemberReference(): ControlDecemberPerson[] {
  if (rows.length !== 42) throw Error("Modelo de Controle: quantidade de pessoas inválida.");
  return rows.map(([name, jobTitle, encoded]) => {
    if (encoded.length !== dates.length || /[^TFPV]/.test(encoded))
      throw Error("Modelo de Controle inválido para " + name);
    const assignments = Object.fromEntries(
      dates.map((day, i) => [
        day,
        controlDecemberCodes[encoded[i] as keyof typeof controlDecemberCodes],
      ]),
    );
    return { name, jobTitle, assignments };
  });
}
