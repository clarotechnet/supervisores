export function rnDecemberReference(sector: string): SchedulePerson[] | null {
  const data = reference[sector];
  const people = data
    ? data.rows.map(([name, login, jobTitle, encoded]) => ({
        name: name!,
        login: login!,
        jobTitle: jobTitle!,
        assignments: Object.fromEntries(
          data.dates.map((day, index) => [day, data.codes[parseInt(encoded![index]!, 36)]!]),
        ),
      }))
    : null;
  const rule = getScheduleGenerationRule(sector === "mossoro" ? "mossoro" : "natal", sector);
  if (!people || !rule?.fixedOffDistribution) return people;
  const balanced = balanceFixedRests(people, "2026-12", rule);
  return balanced.people.map((p, i) => ({
    ...p,
    assignments: {
      ...p.assignments,
      ...Object.fromEntries(
        Object.entries(balanced.outsideAssignments[i] || {}).filter(([d]) => d > "2026-12-31"),
      ),
    },
  }));
}
export function isInitialRnDecember(city: string, sector: string, month: string) {
  return (
    month.slice(0, 7) === "2026-12" &&
    !!reference[sector] &&
    (sector === "mossoro" ? city === "mossoro" : city === "natal")
  );
}
