const key = (name: string) =>
  name
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toUpperCase()
    .replace(/\s+/g, " ")
    .trim();
const fullNames = new Map(names.map(([short, full]) => [key(short), full]));
export function controlFullName(name: string): string {
  return fullNames.get(key(name)) ?? name;
}
export function controlDutyNameAliases(name: string): string[] {
  const full = controlFullName(name);
  const match = names.find(([, value]) => key(value) === key(full));
  return match ? [...new Set([name, match[0], match[1]])] : [name];
}
